import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
const {chromium}=await import(process.env.QA_PLAYWRIGHT_PATH ? pathToFileURL(process.env.QA_PLAYWRIGHT_PATH).href : 'playwright');
await mkdir('qa',{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.QA_CHROME_PATH});
const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const page=await context.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.QA_BASE_URL||'http://127.0.0.1:4173',{waitUntil:'networkidle'});
await page.evaluate(()=>document.fonts.ready);
await page.evaluate(async()=>{for(const image of document.images)image.loading='eager';await Promise.all([...document.images].map(image=>image.decode()));});
await page.screenshot({path:'qa/desktop.png',fullPage:true});
for(const width of [320,375,390,768,1024,1440]){
  await page.setViewportSize({width,height:900});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Desborde horizontal a ${width}px`);
}
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'qa/mobile.png',fullPage:true});
await page.locator('.menu-toggle').click();
assert.equal(await page.locator('.menu-toggle').getAttribute('aria-expanded'),'true');
await page.locator('#navigation a').first().click();
assert.equal(await page.locator('.menu-toggle').getAttribute('aria-expanded'),'false');
await page.locator('.mobile-cta .order-open').click();
assert.equal(await page.locator('#categories button').first().innerText(),'Promociones');
assert.equal(await page.locator('#categories button').first().getAttribute('aria-pressed'),'true');
await page.locator('#categories').getByRole('button',{name:'Pizzas clásicas',exact:true}).click();
await page.getByRole('button',{name:'Sumar Muzzarella',exact:true}).click();
assert.match(await page.locator('#selection-count').innerText(),/1 producto/);
await page.getByRole('button',{name:'Continuar con entrega y datos'}).click();
await page.locator('input[name="mode"][value="takeaway"]').check();
assert.equal(await page.locator('input[name="address"]').evaluate(e=>e.required),false);
assert.equal(await page.locator('#address-fields').isVisible(),false);
await page.locator('input[name="mode"][value="delivery"]').check();
assert.equal(await page.locator('input[name="address"]').evaluate(e=>e.required),true);
await page.locator('input[name="address"]').fill('Dirección de prueba 123');
await page.locator('textarea[name="instructions"]').fill('No funciona el timbre. Llamar antes.');
await page.locator('input[name="phone"]').fill('1112345678');
await page.locator('input[name="timing"][value="scheduled"]').check();
const date=await page.evaluate(async()=>{const {validSchedule,localDate}=await import('./order.js');for(let n=1;n<8;n++){const d=new Date(Date.now()+n*864e5);const s=localDate(d);if(validSchedule(s,'20:00'))return s;}});
await page.locator('input[name="date"]').fill(date);
await page.locator('input[name="time"]').fill('20:00');
await page.getByRole('button',{name:'Ir a pago y revisión'}).click();
assert.equal(await page.locator('#review').isVisible(),true);
assert.match(await page.locator('#review-data').innerText(),/No funciona el timbre/);
assert.equal(await page.locator('#send-order').isDisabled(),false);
await page.screenshot({path:'qa/order-mobile.png',fullPage:false});
await page.getByRole('button',{name:'Editar datos'}).click();
await page.locator('input[name="mode"][value="takeaway"]').check();
await page.getByRole('button',{name:'Ir a pago y revisión'}).click();
assert.doesNotMatch(await page.locator('#review-data').innerText(),/No funciona el timbre|Dirección de prueba/);
assert.match(await page.locator('#review-data').innerText(),/Coucheiro 213/);
await page.getByRole('button',{name:'Editar productos'}).click();
await page.locator('#categories').getByRole('button',{name:'Promociones',exact:true}).click();
for(const width of [320,375,390]){
  await page.setViewportSize({width,height:844});
  assert.ok(await page.locator('#order-dialog').evaluate(e=>e.scrollWidth<=e.clientWidth),`Desborde de carta a ${width}px`);
}
await page.getByRole('button',{name:'Sumar 1 Muzzarella Grande + Media Docena de Empanadas',exact:true}).click();
assert.equal(await page.locator('#to-delivery').isDisabled(),true);
for(let i=0;i<6;i++)await page.getByRole('button',{name:'Añadir sabor',exact:true}).click();
assert.equal(await page.locator('#to-delivery').isDisabled(),false);
await page.screenshot({path:'qa/flavors-mobile.png',fullPage:false});
await page.locator('#to-delivery').click();
await page.getByRole('button',{name:'Ir a pago y revisión'}).click();
assert.match(await page.locator('#review-products').innerText(),/6 de Carne/);
await page.screenshot({path:'qa/order-mobile.png',fullPage:false});
let draft;
await page.route('https://wa.me/**',async route=>{draft=new URL(route.request().url()).searchParams.get('text');await route.fulfill({status:200,contentType:'text/html',body:'Borrador interceptado por QA. No se envió ningún mensaje.'});});
await page.locator('#send-order').click();
await page.waitForURL('https://wa.me/**');
assert.match(draft,/6 de Carne/);
assert.match(draft,/Coucheiro 213/);
assert.doesNotMatch(draft,/Dirección de prueba/);
await page.goBack();
await page.locator('.mobile-cta .order-open').click();
await page.getByRole('button',{name:'Cerrar pedido'}).click();
assert.equal(await page.locator('#order-dialog').evaluate(e=>e.open),false);
assert.deepEqual(errors,[]);
console.log('Verificado: 6 anchos, navegación, carta real, cantidades, delivery 2 km, indicaciones, take away, horario, sabores de combos y revisión. Borrador de WhatsApp interceptado, sin enviar mensajes. Sin errores JS.');
await browser.close();
